function manifestFileMap(manifest) {
  if (!manifest.files || typeof manifest.files !== "object" || Array.isArray(manifest.files)) return null;
  const out = new Map();
  for (const [key, raw] of Object.entries(manifest.files)) {
    const descriptor = typeof raw === "string"
      ? (/^[a-f0-9]{64}$/i.test(raw) ? { path: key, sha256: raw } : { path: raw })
      : (raw && typeof raw === "object" ? { path: key, ...raw } : null);
    if (!descriptor || typeof descriptor.path !== "string" || !descriptor.path.trim()) continue;
    out.set(key, descriptor);
    out.set(descriptor.path.replaceAll("\\", "/"), descriptor);
    out.set(basename(descriptor.path), descriptor);
  }
  return out;
}

function catalogDescriptor(config, rel) {
  return config.fileMap?.get(rel) || null;
}

function catalogFilePath(config, rel) {
  const descriptor = catalogDescriptor(config, rel);
  if (!descriptor) throw new Error(`catalog manifest does not declare ${rel}`);
  const declared = descriptor.path;
  if (isAbsolute(declared)) throw new Error(`catalog manifest path must be relative: ${declared}`);
  const absolute = resolve(config.dir, declared);
  const inside = relative(config.dir, absolute);
  if (!inside || inside.startsWith("..") || isAbsolute(inside))
    throw new Error(`catalog manifest path escapes its directory: ${declared}`);
  return absolute;
}

function validateCatalogFileSchema(rel, value) {
  const entityArrays = new Set([
    "classes.json", "subclasses.json", "species.json", "backgrounds.json",
    "feats.json", "spells.json", "conditions.json",
  ]);
  if (entityArrays.has(rel)) {
    if (!Array.isArray(value)) return `${rel} must contain an array`;
    const invalid = value.findIndex((entry) => !entry || typeof entry !== "object" || typeof entry.id !== "string" || !entry.id);
    return invalid < 0 ? null : `${rel}[${invalid}] must have a non-empty string id`;
  }
  if (rel === "equipment.json") {
    if (!value || typeof value !== "object" || Array.isArray(value)) return `${rel} must contain grouped arrays`;
    for (const group of ["weapons", "armors", "tools", "packs", "gear"])
      if (!Array.isArray(value[group])) return `${rel}.${group} must be an array`;
    return null;
  }
  if (rel === "languages.json") {
    return value && Array.isArray(value.courantes) && Array.isArray(value.rares)
      ? null : `${rel} must contain courantes[] and rares[]`;
  }
  if (rel === "spells-by-class.json") {
    if (!value || typeof value !== "object" || Array.isArray(value)) return `${rel} must contain a class map`;
    return Object.values(value).every(Array.isArray) ? null : `${rel} class entries must be arrays`;
  }
  if (rel === "build-graph.json")
    return value && Array.isArray(value.steps) ? null : `${rel} must contain steps[]`;
  if (rel === "progression.json")
    return value && value.classes && typeof value.classes === "object" ? null : `${rel} must contain a classes object`;
  if (rel.startsWith("labels.") || rel === "ui-labels.json")
    return value && typeof value === "object" && !Array.isArray(value) ? null : `${rel} must contain an object`;
  return null;
}

function validateCatalogSelection(dir, source) {
  const config = {
    source, dir: resolve(dir), manifestPath: resolve(dir, CATALOG_MANIFEST),
    manifest: null, fileMap: null, errors: [], warnings: [],
  };
  try {
    if (!existsSync(config.dir) || !statSync(config.dir).isDirectory())
      throw new Error(`catalog directory does not exist: ${config.dir}`);
    if (!existsSync(config.manifestPath))
      throw new Error(`catalog manifest missing: ${config.manifestPath}`);
    config.manifest = JSON.parse(readFileSync(config.manifestPath, "utf8"));
  } catch (error) {
    config.errors.push(error.message);
    return config;
  }
  const manifest = config.manifest;
  const expected = [
    ["schemaVersion", CATALOG_SCHEMA_VERSION],
    ["profile", CATALOG_PROFILE],
    ["ruleset", CATALOG_RULESET],
    ["license", CATALOG_LICENSE],
  ];
  for (const [key, value] of expected) {
    if (manifest[key] !== value)
      config.errors.push(`catalog manifest ${key} must be ${JSON.stringify(value)} (got ${JSON.stringify(manifest[key])})`);
  }
  if (typeof manifest.version !== "string" || !manifest.version.trim())
    config.errors.push("catalog manifest version must be a non-empty string");
  config.fileMap = manifestFileMap(manifest);
  if (!config.fileMap) {
    config.errors.push("catalog manifest files must be an object of path descriptors");
    return config;
  }
  for (const rel of REQUIRED_CATALOG_FILES)
    if (!catalogDescriptor(config, rel)) config.errors.push(`catalog manifest does not declare ${rel}`);

  const descriptors = [...new Set(config.fileMap.values())];
  for (const descriptor of descriptors) {
    const rel = descriptor.path.replaceAll("\\", "/");
    try {
      const path = catalogFilePath(config, rel);
      if (!existsSync(path) || !statSync(path).isFile()) throw new Error(`catalog file missing: ${path}`);
      const realDir = realpathSync(config.dir);
      const realFile = realpathSync(path);
      const realInside = relative(realDir, realFile);
      if (!realInside || realInside.startsWith("..") || isAbsolute(realInside))
        throw new Error(`catalog file resolves outside its directory: ${rel}`);
      const bytes = readFileSync(path);
      const value = JSON.parse(bytes.toString("utf8"));
      const schemaError = validateCatalogFileSchema(basename(rel), value);
      if (schemaError) throw new Error(`catalog schema error: ${schemaError}`);
      if (descriptor.sha256 != null) {
        if (!/^[a-f0-9]{64}$/i.test(descriptor.sha256))
          throw new Error(`catalog manifest has invalid sha256 for ${rel}`);
        const actual = createHash("sha256").update(bytes).digest("hex");
        if (actual.toLowerCase() !== descriptor.sha256.toLowerCase())
          throw new Error(`catalog checksum mismatch for ${rel}`);
      }
    } catch (error) {
      config.errors.push(error.message);
    }
  }
  return config;
}

function configureCatalog(cliDir = null) {
  const envDir = String(process.env.DND_SKILLS_CATALOG_DIR || "").trim();
  const source = cliDir ? "cli" : envDir ? "environment" : "bundled";
  const dir = cliDir || envDir || BUNDLED_CATALOG_DIR;
  _catalogConfig = validateCatalogSelection(dir, source);
  _catalog = null;
  _dataCache.clear();
  return _catalogConfig;
}

function loadData(rel) {
  if (!_catalogConfig) configureCatalog();
  if (_catalogConfig.errors.length) throw new Error(_catalogConfig.errors.join("; "));
  if (!_dataCache.has(rel)) {
    const path = catalogFilePath(_catalogConfig, rel);
    _dataCache.set(rel, JSON.parse(readFileSync(path, "utf8")));
  }
  return _dataCache.get(rel);
}

