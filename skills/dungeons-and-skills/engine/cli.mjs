/* ---- answer validation -------------------------------------------------
   The resolver treats "answered" as "the key is not null". That is not the
   same as "answered legally": a hallucinated class id (`"class":"warlord"`)
   is non-null, so it drops out of `fixedPending` and the sheet is computed
   from nothing — rendering `undefined` values under a green lint.

   That is the exact failure this whole toolchain exists to prevent, so every
   answered value is checked against the legal option set the resolver itself
   returns, and an unknown id is a hard error, never a silent default. */
const META_KEYS = new Set(["_id", "id", "name", "nom", "alignment", "alignement", "abilityScores", "method", "methode"]);

async function validateAnswers(cat, answers) {
  const problems = [];
  const known = new Set(META_KEYS);

  for (const step of cat.graph.steps) {
    for (const node of step.nodes) {
      known.add(node.id);
      if (node.type !== "single" || !nodeApplies(cat, answers, node)) continue;
      const given = answers[node.id];
      if (given == null) continue;
      const legal = fixedNodeOptions(cat, answers, node).map((o) => o.id);
      if (!legal.includes(given)) {
        problems.push(`Manquant documentaire : "${given}" is not a legal value for "${node.id}". Legal ids: ${legal.join(", ")}`);
      }
    }
  }

  // Options are de-duplicated against everything already granted — including what
  // THIS key granted, and what a downstream choice re-granted from it (rogue
  // expertise draws from rogue skills). Validating a key against options computed
  // while the key is still answered therefore rejects the very ids `options`
  // offered. Re-resolve each answered key against a probe with that key removed.
  // Validate against the MAXIMAL option set — the choices as they stand before any
  // dynamic answer consumes one. `pendingChoices` de-duplicates: a skill you picked
  // disappears from its own list, and a downstream choice (rogue expertise draws
  // from rogue skills) removes more. Checking against the post-answer list rejects
  // the very ids `options` offered. Catching values absent from the CATALOG is what
  // this guard is for; over-picking and duplicates are the `ready` gate's job.
  const base = {};
  for (const k of Object.keys(answers)) if (META_KEYS.has(k) || cat.graph.steps.some((s) => s.nodes.some((n) => n.id === k))) base[k] = answers[k];

  for (const c of pendingChoices(cat, base)) known.add(c.id);
  for (const key of Object.keys(answers)) {
    if (META_KEYS.has(key) || key.startsWith("_")) continue;
    const c = pendingChoices(cat, base).find((x) => x.id === key);
    if (!c) continue;
    known.add(key);
    const legal = (c.options || []).map((o) => o.id);
    if (!legal.length) continue;
    const given = answers[key];
    const seen = new Set();
    for (const v of Array.isArray(given) ? given : [given]) {
      if (!legal.includes(v)) {
        problems.push(`Manquant documentaire : "${v}" is not available for "${key}" — not in the catalog, or another answer already grants it. Legal ids: ${legal.join(", ")}`);
      } else if (seen.has(v)) {
        problems.push(`"${v}" appears twice under "${key}" — each pick must be distinct.`);
      }
      seen.add(v);
    }
  }

  // A misspelled key is silently dropped by the resolver; say so rather than
  // letting the agent believe the answer registered.
  for (const key of Object.keys(answers)) {
    if (!known.has(key) && !key.startsWith("_")) {
      problems.push(`Unknown answer key "${key}" — it is ignored. Run \`options\` to see the exact ids.`);
    }
  }
  return problems;
}

/* ---- options : the next legal choices, straight from the resolver ---- */
/* ---- grounded facts on the three identity choices -------------------------
   `fixedNodeOptions` returns {id, name}, which is all the resolver needs and
   nothing a first-time player can choose from. The skill body used to send the
   agent to `data/classes.json` for a one-line description — 46161 characters,
   not shipped inside the skill folder — so in practice the opening turn came
   from memory. Every field below is COPIED from the catalog entry, never
   computed or reworded, and carries the entry's own ref + source so the
   citation travels with the value. Measured on the 12 classes: 3907 characters
   against 46161 for the file, and 448 for the bare {id, name}. */
const factsFor = (entry, catalogKey) => {
  const eff = entry.effects || [];
  const all = (what) => eff.filter((e) => e.what === what);
  const values = (what) => all(what).map((e) => e.value).filter(Boolean);
  const base = { ref: entry.ref, source: entry.source };

  if (catalogKey === "classes") {
    const cast = all("spellcasting")[0];
    return { ...base,
      hitDie: entry.hitDie,
      primaryAbility: entry.primaryAbility,
      savingThrows: entry.savingThrows,
      armorTraining: values("armorTraining"),
      shieldTraining: all("shieldTraining").length > 0,
      weaponProficiency: values("weaponProficiency"),
      spellcastingAbility: cast ? cast.ability : null,
      level1Features: all("feature").map((e) => e.name).filter(Boolean),
      subclassLevel: (entry.subclass || {}).level ?? null };
  }
  if (catalogKey === "species") {
    // Five of ten species — human, elf, dragonborn, tiefling, aasimar — carry an
    // empty effects[] because what distinguishes them is a CHOICE (a Dragonborn's
    // draconic ancestry, an Elf's lineage). Reporting only effects[] handed the
    // agent "darkvision, and nothing else" for the species a beginner names first,
    // which is precisely when it fills the hole from memory.
    const mappedChoices = (entry.choices || []).map((c) => ({
      id: c.id, kind: c.kind, count: c.count,
      options: (c.from && c.from.fromList) || Object.keys(c.appliesEffects || {}) }));
    const lineages = (entry.lineages || []).map((l) => l.name || l.id);
    // When lineages is empty but an ancetre-draconique choice is present, surface
    // it as a dedicated top-level field so an LLM does not see only `lineages: []`
    // and fall back to memory for the 10 draconic ancestry options.
    const draconicChoice = (entry.choices || []).find((c) => c.kind === "ancetre-draconique");
    const draconicAncestry = (lineages.length === 0 && draconicChoice)
      ? { kind: draconicChoice.kind,
          options: (draconicChoice.from && draconicChoice.from.fromList)
                   || Object.keys(draconicChoice.appliesEffects || {}) }
      : undefined;
    return { ...base,
      size: entry.size,
      speed: entry.speed,
      senses: all("sense").map((e) => [e.value, e.range].filter(Boolean).join(" ")),
      resistances: values("resistance"),
      features: all("feature").map((e) => e.name).filter(Boolean),
      choices: mappedChoices,
      lineages,
      ...(draconicAncestry ? { draconicAncestry } : {}) };
  }
  if (catalogKey === "backgrounds") {
    return { ...base,
      abilityScores: entry.abilityScores,
      skills: entry.skills,
      toolProficiency: entry.toolProficiency,
      feat: entry.feat };
  }
  return null;
};

/* Only the three nodes that draw straight from a catalog list — class, species,
   background. Subclass (level 3), lineage and ability method resolve from an
   already-made choice and need no card. */
function withFacts(cat, node, options) {
  const key = (node.optionsFrom || {}).catalog;
  const list = key && cat[key];
  if (!list) return options;
  return options.map((o) => {
    const entry = list.find((e) => e.id === o.id);
    const facts = entry && factsFor(entry, key);
    return facts ? { ...o, facts } : o;
  });
}

function cmdOptions(answers) {
  const catalog = loadCatalogNodeSync(); // resolver.loadCatalogNode is async; wrap below
  return catalog.then((cat) => {
    const fixed = [];
    for (const step of cat.graph.steps) {
      for (const node of step.nodes) {
        if (!nodeApplies(cat, answers, node)) continue;
        if (node.type === "single" && answers[node.id] == null) {
          fixed.push({ id: node.id, label: node.label, type: "single",
            options: withFacts(cat, node, fixedNodeOptions(cat, answers, node)) });
        } else if (node.type === "ability-scores" && !answers.abilityScores) {
          fixed.push({ id: "abilityScores", label: node.label, type: "ability-scores", methods: cat.graph.abilityMethods });
        }
      }
    }
    const dynamic = pendingChoices(cat, answers)
      .filter((c) => !c.satisfied)
      .map((c) => ({ id: c.id, kind: c.kind, source: c.sourceLabel, need: c.need,
        options: c.options, recommendations: c.recommendations }));
    const ready = fixed.length === 0 && dynamic.length === 0 && !!answers.abilityScores;
    return { ready, fixedPending: fixed, dynamicPending: dynamic };
  });
}

/* One shared, validated catalog per invocation. */
function loadCatalogNodeSync() {
  if (_catalog) return _catalog;
  _catalog = Promise.resolve({
    classes: loadData("classes.json"), subclasses: loadData("subclasses.json"),
    species: loadData("species.json"), backgrounds: loadData("backgrounds.json"),
    feats: loadData("feats.json"), equipment: loadData("equipment.json"),
    spells: loadData("spells.json"), spellsByClass: loadData("spells-by-class.json"),
    languages: loadData("languages.json"), conditions: loadData("conditions.json"),
    graph: loadData("build-graph.json"),
  });
  return _catalog;
}

/* ---- catalog cross-checks the pure engine cannot make (it never reads data/) ----
   A prepared spell above the highest slot level the class has at the sheet's level,
   or a "cantrip" that is not level 0 in the catalog, is a hard error. Slot ceilings
   come from data/progression.json (extracted from the class tables), spell levels
   from data/spells.json. Lists that are not a class in the progression (e.g. the
   species list) are outside class slots and are not capped here. */
function spellLevelProblems(C, catalog = null) {
  const problems = [];
  let spells, progression, byClass;
  try {
    spells = catalog ? catalog.spells : loadData("spells.json");
    progression = loadData("progression.json");
    byClass = catalog ? catalog.spellsByClass : loadData("spells-by-class.json");
  } catch { return problems; } // no catalog beside the engine: nothing to cross-check
  const byId = new Map(spells.map((s) => [s.id, s]));

  /* List membership was never checked anywhere, so a level-1 Cleric whose four
     chosen cantrips were Wizard-only — filed under `list: "cleric"` — linted
     clean and exited 0. Two skills define "legal" as "0 sheet-lint errors" and
     dnd-check's description promises to flag "a skill on the wrong list".

     Scoped deliberately: only the eight lists spells-by-class.json actually
     defines. A sheet's `list` is also legitimately `espece` (species-granted) or
     `initie-clerc` (the Magic Initiate feat), which name no catalog list. Mapping
     `initie-clerc` -> `cleric` would be a guess, and guessing is the one thing
     this engine refuses; those lists are reported as unverified instead. */
  const onList = new Map(Object.entries(byClass).map(([k, v]) => [k, new Set(v.map((e) => e.id))]));
  const unverified = new Set();
  const checkMembership = (s, kind) => {
    const set = onList.get(s.list);
    if (!set) { if (s.list) unverified.add(s.list); return; }
    if (!set.has(s.id)) {
      problems.push({ level: "error", code: "spell-list-membership",
        params: { kind, spell: s.id, list: s.list },
        msg: `${kind} ${s.id}: absent de la liste "${s.list}" (data/spells-by-class.json)` });
    }
  };
  const maxSlotFor = (list) => {
    const cls = progression.classes && progression.classes[list];
    const row = cls && cls.levels && cls.levels[(C.lvl || 1) - 1];
    if (!row) return null;
    if (row.pact) return row.pact.level;
    if (row.slots) return Math.max(...Object.keys(row.slots).map(Number));
    return 0;
  };
  for (const s of C.cantrips) {
    checkMembership(s, "sort mineur");
    const cat = byId.get(s.id);
    if (!cat) { problems.push({ level: "warn", code: "spell-catalog-missing",
      params: { kind: "cantrip", spell: s.id }, msg: `sort mineur ${s.id}: absent du catalogue (Manquant documentaire)` }); continue; }
    if (cat.level !== 0) problems.push({ level: "error", code: "cantrip-level-invalid",
      params: { spell: s.id, level: cat.level }, msg: `sort mineur ${s.id}: niveau ${cat.level} dans le catalogue, un sort mineur doit etre de niveau 0` });
  }
  for (const s of C.prepared) {
    checkMembership(s, "sort prepare");
    const cat = byId.get(s.id);
    if (!cat) { problems.push({ level: "warn", code: "spell-catalog-missing",
      params: { kind: "prepared spell", spell: s.id }, msg: `sort prepare ${s.id}: absent du catalogue (Manquant documentaire)` }); continue; }
    const max = maxSlotFor(s.list);
    if (max != null && cat.level > max) {
      problems.push({ level: "error", code: "spell-level-unavailable",
        params: { spell: s.id, level: cat.level, max, list: s.list, characterLevel: C.lvl },
        msg: `sort prepare ${s.id}: niveau ${cat.level} > emplacement max ${max} (${s.list} niveau ${C.lvl}, source: progression.json)` });
    }
  }
  // Say what was NOT checked rather than let a clean lint imply it was.
  if (unverified.size) {
    problems.push({ level: "warn", code: "spell-list-unverified",
      params: { lists: [...unverified].sort().join(", ") },
      msg: `appartenance non verifiee pour ${[...unverified].sort().join(", ")} : ces listes ne sont pas definies dans data/spells-by-class.json — a controler a la main` });
  }
  return problems;
}

/* ---- machine-readable summary of a computed character (for build/check --json) ---- */
function summarize(C) {
  return {
    id: C.model.id || null,
    classId: C.model.classId || null,
    speciesId: C.model.speciesId || null,
    lineageId: C.model.lineageId || null,
    backgroundId: C.model.backgroundId || null,
    identity: C.model.identity || {}, level: C.lvl, pb: C.PB,
    scores: C.scores, mods: C.mods,
    sources: C.model.sources || [], choices: C.model.choices || [],
    derived: C.derived, saves: C.saves, skills: C.skills,
    features: C.features, casting: C.castingRows,
    counters: C.counters,
    cantrips: C.cantrips, prepared: C.prepared,
    equipment: C.model.equipment || [],
    missing: C.missing, conflicts: C.conflicts, problems: C.problems,
  };
}

/* Older checked models predate the stable catalog IDs used by the renderers.
   Resolve them from catalog names only when the match is unique; an uncertain
   mapping stays visible as a structured warning instead of silently selecting
   the first plausible entry. */
function resolveLegacyModelIds(cat, model) {
  const legacyAliases = {
    classId: {
      barbare: "barbarian", barde: "bard", clerc: "cleric", druide: "druid",
      guerrier: "fighter", moine: "monk", paladin: "paladin", rodeur: "ranger",
      roublard: "rogue", ensorceleur: "sorcerer", occultiste: "warlock", magicien: "wizard",
    },
    speciesId: {
      drakeide: "dragonborn", nain: "dwarf", elfe: "elf", gnome: "gnome",
      goliath: "goliath", halfelin: "halfling", humain: "human", orc: "orc", tieffelin: "tiefling",
    },
    backgroundId: { acolyte: "acolyte", criminel: "criminal", sage: "sage", soldat: "soldier" },
  };
  const warnings = [];
  const warn = (field, value, reason) => warnings.push({
    level: "warn",
    code: "legacy-id-unresolved",
    params: { entity: field, label: value ?? "", reason },
    msg: `ancien modèle : ${field} "${value ?? ""}" ${reason === "ambiguous" ? "est ambigu" : "ne correspond à aucune entrée du catalogue"}`,
  });
  const resolveUnique = (entries, value, field) => {
    if (!value) return null;
    const wanted = normId(value);
    const alias = legacyAliases[field]?.[wanted];
    if (alias) {
      const matched = (entries || []).filter((entry) => entry.id === alias);
      if (matched.length === 1) return matched[0];
    }
    let matches = (entries || []).filter((entry) =>
      [entry.id, entry.name, entry.label].some((candidate) => candidate && normId(candidate) === wanted));
    if (!matches.length) {
      matches = (entries || []).filter((entry) =>
        [entry.id, entry.name, entry.label].some((candidate) => {
          const token = candidate ? normId(candidate) : "";
          return token && (wanted.startsWith(`${token}-`) || token.startsWith(`${wanted}-`));
        }));
    }
    if (matches.length === 1) return matches[0];
    warn(field, value, matches.length > 1 ? "ambiguous" : "missing");
    return null;
  };

  const cls = model.classId ? null : resolveUnique(cat.classes, model.identity?.className, "classId");
  const species = model.speciesId ? null : resolveUnique(cat.species, model.identity?.species, "speciesId");
  const background = model.backgroundId ? null : resolveUnique(cat.backgrounds, model.identity?.background, "backgroundId");
  if (cls) model.classId = cls.id;
  if (species) model.speciesId = species.id;
  if (background) model.backgroundId = background.id;

  if (!model.lineageId && model.identity?.lineage) {
    const lineages = (cat.species || []).flatMap((entry) =>
      (entry.lineages || []).map((lineage) => ({ ...lineage, speciesId: entry.id })));
    const lineage = resolveUnique(lineages, model.identity.lineage, "lineageId");
    if (lineage) model.lineageId = lineage.id;
  }

  const sourceCatalogs = {
    "class-level": [cat.classes, model.classId],
    species: [cat.species, model.speciesId],
    lineage: [(cat.species || []).flatMap((entry) => entry.lineages || []), model.lineageId],
    background: [cat.backgrounds, model.backgroundId],
    feat: [cat.feats, null],
    subclass: [cat.subclasses, null],
  };
  for (const source of model.sources || []) {
    if (source.catalogId) continue;
    if (source.id === "origine-langues") {
      source.catalogId = "origin-languages";
      continue;
    }
    const spec = sourceCatalogs[source.kind];
    if (!spec) continue;
    if (spec[1]) {
      source.catalogId = spec[1];
      continue;
    }
    const entry = resolveUnique(spec[0], source.label || source.id, `sources.${source.id}.catalogId`);
    if (entry) source.catalogId = entry.id;
  }

  const equipmentEntries = Object.values(cat.equipment || {})
    .filter(Array.isArray).flat();
  const roleIds = {
    bouclier: "shield", shield: "shield", armure: "armor", armor: "armor",
    arme: "weapon", weapon: "weapon", outil: "tool", tool: "tool",
    paquetage: "pack", pack: "pack", "focaliseur-dincantation": "spellcasting-focus",
    "spellcasting-focus": "spellcasting-focus", objet: "gear", gear: "gear",
  };
  for (const item of model.equipment || []) {
    let entry = null;
    if (!item.id) {
      entry = resolveUnique(equipmentEntries, item.object, `equipment.${item.object}.id`);
      if (entry) item.id = entry.id;
    } else {
      entry = equipmentEntries.find((candidate) => candidate.id === item.id) || null;
    }
    if (!item.roleIds && item.roles) {
      item.roleIds = item.roles.map((role) => roleIds[normId(role)]).filter(Boolean);
    }
    if (!item.damageType && entry?.damageType) item.damageType = entry.damageType;
  }
  return warnings;
}

/* ---- markdown sheet ---- */
function renderSheet(C, lang, labels) {
  const L = makeLabeler(lang, labels);
  const ui = loadUiLabels();
  const t = ui[lang] || ui.en || {};
  const id = C.model.identity || {};
  const A = ["str", "dex", "con", "int", "wis", "cha"];
  const out = [];

  const clsName = L.map("classes", (C.model.sources.find((s) => s.kind === "class-level") || {}).id, id.className);
  const spName = L.map("species", (C.model.sources.find((s) => s.kind === "species") || {}).id, id.species);
  out.push(`# ${id.name || "?"}`);
  out.push(`*${spName || "?"}${id.lineage ? " (" + id.lineage + ")" : ""}, ${clsName || "?"} ${t.level} ${C.lvl}${id.background ? ", " + id.background : ""}.*`);
  out.push("");

  // ability scores
  out.push("| " + A.map((a) => L.abil(a).slice(0, 3)).join(" | ") + " |");
  out.push("|" + A.map(() => "---").join("|") + "|");
  out.push("| " + A.map((a) => `${C.scores[a] ?? "?"} (${sign(C.mods[a])})`).join(" | ") + " |");
  out.push("");

  // core derived
  const pick = (name) => C.derived.find((d) => d.name === name);
  const core = [
    [t.pb, sign(C.PB), `PB`],
    [t.hp, (pick("Points de vie") || {}).value, (pick("Points de vie") || {}).prov],
    [t.ac, (pick("CA") || {}).value, (pick("CA") || {}).prov],
    [t.init, (pick("Initiative") || {}).value, `mod Dex`],
    [t.pp, (pick("Perception passive") || {}).value, (pick("Perception passive") || {}).prov],
  ];
  for (const [k, v, prov] of core) out.push(`- **${k}**: ${v} _(${t.provenance}: ${prov})_`);
  out.push("");

  // saves
  out.push(`## ${t.saves}`);
  out.push(C.saves.map((s) => `${L.abil(s.a).slice(0, 3)} ${sign(s.total)}${s.prof ? "*" : ""}`).join(" · "));
  out.push("");

  // skills (proficient only, to stay under Vercel-style volume discipline)
  const prof = C.skills.filter((s) => s.prof);
  if (prof.length) {
    out.push(`## ${t.skills}`);
    out.push(prof.map((s) => `${L.map("skills", s.name, s.name)} ${sign(s.total)}${s.exp ? "**" : "*"} _(${s.src || ""})_`).join("\n"));
    out.push("");
  }

  // features
  if (C.features && C.features.length) {
    out.push(`## ${t.features}`);
    out.push(C.features.map((f) => `- **${f.name}**${f.note ? `: ${f.note}` : ""} _(${f.src || ""})_`).join("\n"));
    out.push("");
  }

  // proficiencies: armor / weapons / shield
  const armorLine = (C.armorTraining || []).join(", ");
  const weaponLine = (C.weaponProf || []).map((w) => w.v).join(", ");
  const shieldLine = C.hasShieldTraining ? t.shield : "";
  if (armorLine || weaponLine || shieldLine) {
    out.push(`## ${t.proficiencies}`);
    if (armorLine) out.push(`**${t.armor}**: ${armorLine}`);
    if (weaponLine) out.push(`**${t.weapons}**: ${weaponLine}`);
    if (shieldLine) out.push(`**${shieldLine}**`);
    out.push("");
  }

  // tools
  if (C.tools && C.tools.length) {
    out.push(`## ${t.tools}`);
    out.push(C.tools.map((tl) => `- ${tl.v} _(${tl.src || ""})_`).join("\n"));
    out.push("");
  }

  // languages
  if (C.languages && C.languages.length) {
    out.push(`## ${t.languages}`);
    out.push(C.languages.map((lg) => `- ${lg.v} _(${lg.src || ""})_`).join("\n"));
    out.push("");
  }

  // spells
  if (C.cantrips.length || C.prepared.length) {
    out.push(`## ${t.spells}`);
    C.castingRows.forEach((r) => out.push(`- ${r.list}: DC ${r.dc} / atk ${sign(r.atk)}`));
    if (C.cantrips.length) out.push(`**${t.cantrips}**: ` + C.cantrips.map((s) => L.map("spells", s.id, s.label || s.id)).join(", "));
    if (C.prepared.length) out.push(`**${t.prepared}**: ` + C.prepared.map((s) => L.map("spells", s.id, s.label || s.id)).join(", "));
    out.push("");
  }

  // equipment
  if ((C.model.equipment || []).length) {
    out.push(`## ${t.equipment}`);
    out.push(C.model.equipment.map((e) => `- ${e.object} (${(e.roles || []).join(", ")})`).join("\n"));
    out.push("");
  }

  // combat summary (niveau 1)
  // All values are grounded: counters from progression.json, spell counts from
  // the built model, slots from progression.json. Nothing is inferred from memory.
  const classSrc = C.model.sources.find((s) => s.kind === "class-level");
  if (classSrc) {
    const classId = classSrc.id;
    let lvl1 = null;
    try {
      const prog = loadData("progression.json");
      const cls = prog && prog.classes && prog.classes[classId];
      lvl1 = cls && cls.levels && cls.levels[0];
    } catch { /* progression.json unavailable: skip combat section */ }

    if (lvl1) {
      out.push(`## ${t.combat}`);

      // 1. Standard actions. No structured action-type effects exist in the catalog
      //    (effects[] carries grants/requires/requiresChoice but no "action" what).
      //    The spec instructs to show the standard line when no special action data
      //    is present — this is the fallback, not an invented value.
      out.push(`- **${t.actions}** : ${t.actionsStd}`);

      // 2. Resources: named counters at level 1 from the class table.
      //    provenance: progression.json → classId, level 1.
      const cEntries = Object.entries(lvl1.counters || {});
      if (cEntries.length) {
        const resLine = cEntries.map(([k, v]) => `${k} × ${v}`).join(", ");
        out.push(`- **${t.resources}** : ${resLine} _(${t.provenance}: progression.json → ${classId})_`);
      }

      // 3. Spells: only for classes that have casting rows in the model.
      if (C.castingRows && C.castingRows.length) {
        const spellParts = [];
        const cantripCount = C.cantrips.length;
        const preparedCount = C.prepared.length;
        if (cantripCount) spellParts.push(`${cantripCount} ${t.cantrips.toLowerCase()}`);
        if (preparedCount) spellParts.push(`${preparedCount} ${t.prepared.toLowerCase()}`);
        const slots = lvl1.slots || {};
        if (Object.keys(slots).length) {
          const slotStr = Object.entries(slots).map(([sl, n]) => `niv.${sl}×${n}`).join(", ");
          spellParts.push(`${t.slots} : ${slotStr}`);
        }
        const pact = lvl1.pact || {};
        if (pact.slots) {
          spellParts.push(`${t.pactSlots} : ${pact.slots}×niv.${pact.level}`);
        }
        if (spellParts.length) {
          out.push(`- **${t.spells}** : ${spellParts.join(", ")} _(${t.provenance}: progression.json → ${classId})_`);
        }
      }

      out.push("");
    }
  }

  // remaining / conflicts / lint
  out.push(`## Lint`);
  out.push(`- ${t.remaining}: ${C.missing.length ? C.missing.map((m) => `${m.kind}×${m.count}`).join(", ") : t.none}`);
  out.push(`- ${t.conflicts}: ${C.conflicts.length ? C.conflicts.map((c) => c.what).join(", ") : t.none}`);
  const errs = C.problems.filter((p) => p.level === "error");
  out.push(errs.length ? `- ⛔ ${errs.length} ${t.lintErr}: ${errs.map((p) => p.msg).join(" ; ")}` : `- ✅ ${t.lintOk}`);
  // Warnings were computed and then dropped from the rendered sheet, so the
  // engine's own "Manquant documentaire" never reached anyone — which is how a
  // shipped reference character carried a spell id that exists nowhere in the
  // catalog. A clean-looking sheet must not hide what the engine could not verify.
  const warns = C.problems.filter((p) => p.level === "warn");
  if (warns.length) out.push(`- ⚠ ${warns.length} avertissement(s): ${warns.map((p) => p.msg).join(" ; ")}`);
  return out.join("\n");
}

