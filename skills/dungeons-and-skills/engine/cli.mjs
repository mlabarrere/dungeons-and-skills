const USAGE = 3;

/* Indentation doubles every payload — the opening `options` call is 25818 characters
   pretty against 13048 compact, and harnesses truncate silently between 10K and 30K.
   Indent only what is small enough to stay well outside that band; JSON.parse does
   not care either way. */
function emit(obj) {
  const compact = JSON.stringify(obj);
  console.log(compact.length > 8000 ? compact : JSON.stringify(obj, null, 2));
}

const COMMANDS = ["options", "build", "check", "progression", "doctor"];
const LANGS = ["en", "fr", "de", "es", "it", "ja", "ru", "zh", "ar"];

function packageVersion() {
  try {
    const version = JSON.parse(readFileSync(new URL("../version.json", import.meta.url), "utf8"));
    if (typeof version.version === "string" && version.version) return version.version;
  } catch { /* installed legacy bundles may not carry version.json */ }
  return "unknown";
}

function parseGlobalArgs(argv) {
  const rest = [];
  let catalog = null;
  let version = false;
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === "--version") {
      if (version) throw new Error("--version was provided more than once");
      version = true;
      continue;
    }
    if (arg === "--catalog" || arg.startsWith("--catalog=")) {
      if (catalog !== null) throw new Error("--catalog was provided more than once");
      const inline = arg.startsWith("--catalog=") ? arg.slice("--catalog=".length) : null;
      const value = inline !== null ? inline : argv[++i];
      if (!value || value.startsWith("--")) throw new Error("--catalog requires a directory path");
      catalog = value;
      continue;
    }
    rest.push(arg);
  }
  if (version && rest.length) throw new Error("--version cannot be combined with a command or other arguments");
  return { argv: rest, catalog, version };
}

/* "Reject ambiguous input with a clear error rather than guessing." A mistyped flag
   used to be ignored: `build --jsonn` printed a markdown sheet and exited 0, so an
   agent that asked for JSON got prose with nothing to tell it why. */
const FLAGS = {
  options: ["--brief", "--only"],
  build: ["--format", "--lang", "--output", "--json"],
  check: ["--format", "--lang", "--output", "--json"],
  progression: [], doctor: ["--json"],
};
function rejectUnknownFlags(cmd, rest) {
  const legal = FLAGS[cmd] || [];
  for (const a of rest) {
    if (!a.startsWith("--")) continue;
    const name = a.split("=")[0];
    if (legal.includes(name)) continue;
    console.error(`dnd: unknown flag "${name}" for \`${cmd}\`. Legal flags: ${legal.join(" ") || "(none)"}.`);
    process.exit(USAGE);
  }
}

function readJSON(path) {
  let raw;
  try {
    raw = readFileSync(path, "utf8");
  } catch (e) {
    const why = e.code === "ENOENT" ? "no such file" : e.code === "EISDIR" ? "that is a directory" : e.code;
    console.error(`dnd: cannot read "${path}" (${why}). Expected a JSON file.`);
    process.exit(USAGE);
  }
  try {
    return JSON.parse(raw);
  } catch (e) {
    console.error(`dnd: "${path}" is not valid JSON (${e.message}).`);
    process.exit(USAGE);
  }
}

/* --lang accepts a closed set. Guessing silently is how `--lang=en` came to
   render French and `--lang klingon` to render English, both exiting 0. */
function parseLang(rest) {
  let value = null;
  for (let i = 0; i < rest.length; i++) {
    const a = rest[i];
    if (a === "--lang") { value = rest[i + 1] ?? ""; break; }
    if (a.startsWith("--lang=")) { value = a.slice("--lang=".length); break; }
  }
  if (value === null) return "en";
  if (!LANGS.includes(value)) {
    console.error(`dnd: unknown --lang "${value}". Legal values: ${LANGS.join(" ")}.`);
    process.exit(USAGE);
  }
  return value;
}

/* build/check share one closed, strict output contract. Values may use either
   `--flag value` or `--flag=value`; duplicate/conflicting declarations are
   rejected instead of depending on argument order. */
function parseRenderOptions(rest, cmd) {
  let lang = null;
  let format = null;
  let output = null;
  let jsonAlias = false;

  const setOnce = (name, current, value) => {
    if (current !== null) {
      console.error(`dnd: ${name} was provided more than once.`);
      process.exit(USAGE);
    }
    return value;
  };
  const takeValue = (arg, name, i) => {
    if (arg === name) {
      const value = rest[i + 1];
      if (value == null || value.startsWith("--")) {
        console.error(`dnd: ${name} requires a value.`);
        process.exit(USAGE);
      }
      return { value, consumed: 1 };
    }
    if (arg.startsWith(name + "=")) return { value: arg.slice(name.length + 1), consumed: 0 };
    return null;
  };

  for (let i = 0; i < rest.length; i++) {
    const arg = rest[i];
    if (arg === "--json") {
      if (jsonAlias) {
        console.error("dnd: --json was provided more than once.");
        process.exit(USAGE);
      }
      jsonAlias = true;
      continue;
    }
    let parsed = takeValue(arg, "--lang", i);
    if (parsed) {
      lang = setOnce("--lang", lang, parsed.value);
      i += parsed.consumed;
      continue;
    }
    parsed = takeValue(arg, "--format", i);
    if (parsed) {
      format = setOnce("--format", format, parsed.value);
      i += parsed.consumed;
      continue;
    }
    parsed = takeValue(arg, "--output", i);
    if (parsed) {
      output = setOnce("--output", output, parsed.value);
      i += parsed.consumed;
      continue;
    }
    const legal = FLAGS[cmd].join(" ");
    console.error(arg.startsWith("--")
      ? `dnd: unknown flag "${arg.split("=")[0]}" for \`${cmd}\`. Legal flags: ${legal}.`
      : `dnd: unexpected argument "${arg}" for \`${cmd}\`.`);
    process.exit(USAGE);
  }

  lang ||= "en";
  if (!LANGS.includes(lang)) {
    console.error(`dnd: unknown --lang "${lang}". Legal values: ${LANGS.join(" ")}.`);
    process.exit(USAGE);
  }
  if (format !== null && !["html", "markdown", "json"].includes(format)) {
    console.error(`dnd: unknown --format "${format}". Legal values: html markdown json.`);
    process.exit(USAGE);
  }
  if (jsonAlias && format !== null && format !== "json") {
    console.error(`dnd: --json conflicts with --format ${format}. Use one output format.`);
    process.exit(USAGE);
  }
  format = jsonAlias ? "json" : (format || (cmd === "build" ? "html" : "markdown"));
  if (output !== null && format === "json") {
    console.error("dnd: --output cannot be used with JSON output; JSON is written to stdout.");
    process.exit(USAGE);
  }
  return { lang, format, output };
}

function standaloneAssets() {
  const css = readFileSync(new URL("../assets/ds.css", import.meta.url), "utf8");
  const print = readFileSync(new URL("../assets/ds.print.css", import.meta.url), "utf8");
  const js = readFileSync(new URL("../assets/ds.js", import.meta.url), "utf8");
  // A standalone document must not retain ds.css's relative print dependency.
  const expandedCss = css.replace(
    /^\s*@import\s+["']ds\.print\.css["']\s+print\s*;\s*/m,
    `\n@media print {\n${print}\n}\n`,
  );
  return { css: expandedCss, js };
}

function displaySource(file) {
  const rel = relative(process.cwd(), resolve(file));
  return (rel || basename(resolve(file))).replaceAll("\\", "/");
}

function defaultOutputPath(file, cmd, lang, format) {
  const absoluteInput = resolve(file);
  const fileName = basename(absoluteInput);
  const suffix = cmd === "build" ? ".answers.json" : ".character.json";
  const stem = fileName.toLowerCase().endsWith(suffix)
    ? fileName.slice(0, -suffix.length)
    : fileName.toLowerCase().endsWith(".json")
      ? fileName.slice(0, -5)
      : fileName;
  const kind = cmd === "build" ? "sheet" : "audit";
  const extension = format === "html" ? "html" : "md";
  return resolve(dirname(absoluteInput), `${stem}.${kind}.${lang}.${extension}`);
}

function resolveOutputPath(file, cmd, options) {
  const outputPath = options.output
    ? resolve(options.output)
    : defaultOutputPath(file, cmd, options.lang, options.format);
  if (outputPath === resolve(file)) {
    console.error("dnd: refusing to overwrite the input file; choose a different --output path.");
    process.exit(USAGE);
  }
  const wanted = options.format === "html" ? ".html" : ".md";
  if (extname(outputPath).toLowerCase() !== wanted) {
    console.error(`dnd: ${options.format} output must use the "${wanted}" extension.`);
    process.exit(USAGE);
  }
  return outputPath;
}

/* ---- doctor : report the installation as it actually is ------------------
   Every count here is read from disk at call time. The alternative — writing
   the numbers into prose — is what let the skill pack ship a stale roster and
   stale catalog counts: duplicated state always drifts, and nothing notices. */
// Every file the resolver actually needs. Omitting build-graph/equipment/
// spells-by-class made doctor report a healthy bundle that could not build a
// single sheet — the one situation the command exists to detect.
// `Object.keys(j).length` is right only for a flat id->entry map. Applied to a
// grouped file it counts the *groups* — doctor reported "3 languages" for 19 and
// "6 equipment" for 131, and a test that recomputed with the same expression
// could not notice. Each grouped file therefore names its own counter, and
// `show: false` keeps plumbing (the build graph, the per-class spell index) out
// of the human line while still health-checking it.
const sumGroups = (skip) => (j) =>
  Object.entries(j).reduce((n, [k, v]) => (skip.includes(k) || !Array.isArray(v) ? n : n + v.length), 0);

const ENTITY_FILES = [
  ["classes", "classes.json"], ["subclasses", "subclasses.json"], ["species", "species.json"],
  ["backgrounds", "backgrounds.json"], ["feats", "feats.json"], ["spells", "spells.json"],
  ["conditions", "conditions.json"],
  ["languages", "languages.json", sumGroups(["ref"])],
  ["equipment", "equipment.json", sumGroups(["_meta"])],
  ["spellsByClass", "spells-by-class.json", (j) => Object.keys(j).length, false],
  ["graphSteps", "build-graph.json", (j) => (j.steps || []).length, false],
];
const LANGS_ALL = ["en", "fr", "de", "es", "it", "ja", "ru", "zh", "ar"];

function cmdDoctor() {
  const selected = _catalogConfig || configureCatalog();
  const manifest = selected.manifest || {};
  const report = {
    healthy: selected.errors.length === 0,
    node: process.version,
    version: packageVersion(),
    engine: fileURLToPath(import.meta.url),
    catalog: selected.dir,
    catalogPath: selected.dir,
    catalogSource: selected.source,
    catalogManifest: selected.manifestPath,
    manifestValid: selected.errors.length === 0,
    catalogSchemaVersion: manifest.schemaVersion ?? null,
    catalogProfile: manifest.profile ?? null,
    catalogVersion: manifest.version ?? null,
    catalogRuleset: manifest.ruleset ?? null,
    catalogLicense: manifest.license ?? null,
    license: manifest.license ?? null,
    counts: {},
    labels: {},
    warnings: [...selected.errors, ...selected.warnings],
  };

  for (const [name, f, count] of ENTITY_FILES) {
    try {
      const j = loadData(f);
      report.counts[name] = count ? count(j) : Array.isArray(j) ? j.length : Object.keys(j).length;
      // "Readable" is not "usable": an empty array parses fine and resolves nothing.
      if (!report.counts[name]) {
        report.healthy = false;
        report.warnings.push(`data/${f} parses but is empty — the engine cannot resolve anything from it`);
      }
    } catch {
      report.counts[name] = null;
      report.healthy = false;
      report.warnings.push(`catalog file missing or unreadable: data/${f}`);
    }
  }

  try { report.counts.progressionClasses = Object.keys(loadData("progression.json").classes || {}).length; }
  catch { report.counts.progressionClasses = null; report.warnings.push("data/progression.json missing — level 1-20 milestones unavailable"); }

  // Label coverage, per language, against the union of groups any language has.
  const groupsSeen = new Set();
  const perLang = {};
  for (const l of LANGS_ALL) {
    try {
      const j = loadData(`labels.${l}.json`);
      const groups = Object.keys(j).filter((k) => !k.startsWith("_"));
      groups.forEach((g) => groupsSeen.add(g));
      perLang[l] = groups;
    } catch { perLang[l] = null; report.warnings.push(`missing display labels: data/labels.${l}.json`); }
  }
  for (const l of LANGS_ALL) {
    if (!perLang[l]) { report.labels[l] = null; continue; }
    // `abil()` carries a hardcoded English table, so a missing `abilities` group
    // costs an English reader nothing. Reporting it anyway produced the useless
    // "those names fall back to English" against labels.en.json.
    const covered = (g) => perLang[l].includes(g) || (l === "en" && g === "abilities");
    const missing = [...groupsSeen].filter((g) => !covered(g));
    report.labels[l] = { groups: perLang[l].length, missingGroups: missing };
    // The catalog is authored in French, so an untranslated name is shown as-is —
    // French for every group but `abilities`, which has an English fallback table.
    if (missing.length) report.warnings.push(`labels.${l}.json has no ${missing.join(", ")} group — those names are shown untranslated`);
  }
  /* The loop above measures each language against `groupsSeen` — the union of
     what some language happens to have. A group absent from all nine is
     therefore invisible to it, which is how `feats` and `conditions` came to
     have zero labels in every language while doctor reported nine complete.
     The catalog files are the honest denominator: an entity type with no labels
     cannot be looked up by an English (or German, or Japanese) name at all. */
  const LABELLED = [["feats", "feats.json"], ["conditions", "conditions.json"],
    ["spells", "spells.json"], ["classes", "classes.json"], ["species", "species.json"],
    ["backgrounds", "backgrounds.json"], ["subclasses", "subclasses.json"]];
  report.unlabelled = [];
  for (const [group, f] of LABELLED) {
    if (report.counts[group] == null) continue;
    const anywhere = LANGS_ALL.some((l) => perLang[l] && perLang[l].includes(group));
    if (!anywhere) {
      report.unlabelled.push(group);
      report.warnings.push(
        `no language has a "${group}" label group — those ${report.counts[group]} entries are ` +
        `reachable only by their catalog (French) name, whatever --lang says`);
    }
  }

  /* Metadata is not text. Every spell carries level/school/range/components and
     no description, so "what does this spell do" has no catalog answer — the
     single question most likely to be filled in from memory. */
  try {
    const sp = loadData("spells.json");
    const list = Array.isArray(sp) ? sp : Object.values(sp);
    const DESC = ["description", "desc", "text", "effect", "effects", "summary"];
    if (list.length && !list.some((s) => DESC.some((k) => s[k]))) {
      report.warnings.push(
        `data/spells.json carries metadata only (level, school, range, components, classes) — ` +
        `no spell effect text. Answer "what does it do" with "Manquant documentaire", never from memory`);
    }
  } catch { /* the per-file loop above already recorded this */ }

  return report;
}

async function run() {
  if (process.argv.slice(2).length === 1 && process.argv[2] === "--help") {
    console.log(`Dungeons & Skills ${packageVersion()}
Level-1 D&D 2024 builder/checker using the bundled SRD 5.2.1 catalog.
Progression lookup covers class milestones at levels 1-20.

Usage:
  node engine/cli.mjs options <answers.json> [--catalog DIR]
  node engine/cli.mjs build <answers.json> [--format html|markdown|json] [--lang CODE] [--output FILE] [--catalog DIR]
  node engine/cli.mjs check <character.json> [--format html|markdown|json] [--lang CODE] [--output FILE] [--catalog DIR]
  node engine/cli.mjs progression <classId|subclassId> [--catalog DIR]
  node engine/cli.mjs doctor [--json] [--catalog DIR]
  node engine/cli.mjs --version`);
    return;
  }
  let invocation;
  try {
    invocation = parseGlobalArgs(process.argv.slice(2));
  } catch (error) {
    console.error(`dnd: ${error.message}.`);
    process.exit(USAGE);
  }
  if (invocation.version) {
    console.log(`dungeons-and-skills ${packageVersion()}`);
    return;
  }
  configureCatalog(invocation.catalog);
  const [cmd, file, ...rest] = invocation.argv;

  if (cmd === "doctor") {
    // Three skill bodies documented "exit 3 -> you mistyped the command; doctor
    // takes no arguments". doctor ignored them and exited 0, so the branch was
    // unreachable and `doctor --lang en` silently did nothing.
    const doctorArgs = invocation.argv.slice(1);
    const extra = doctorArgs.filter((a) => a !== "--json");
    if (extra.length) {
      console.error(`dnd: doctor takes no arguments (got ${extra.map((a) => JSON.stringify(a)).join(" ")}). ` +
        "It reads the catalog off disk and reports what is there; --lang does not apply.");
      process.exit(USAGE);
    }
    const r = cmdDoctor();
    if (doctorArgs.includes("--json")) {
      console.log(JSON.stringify(r, null, 2));
    } else {
      console.log(`Dungeons & Skills — installation report`);
      console.log(`  node     ${r.node}`);
      console.log(`  version  ${r.version}`);
      console.log(`  engine   ${r.engine}`);
      console.log(`  catalog  ${r.catalog} (${r.catalogSource})`);
      console.log(`  profile  ${r.catalogProfile || "?"} catalog ${r.catalogVersion || "?"} schema ${r.catalogSchemaVersion ?? "?"}`);
      // The human line lists what a player would recognise; `--json` carries
      // everything, plumbing included.
      const hidden = new Set(ENTITY_FILES.filter(([, , , show]) => show === false).map(([n]) => n));
      const shown = Object.entries(r.counts).filter(([k]) => !hidden.has(k));
      console.log(`  catalog contents: ${shown.map(([k, v]) => `${v ?? "?"} ${k}`).join(", ")}`);
      const ok = Object.entries(r.labels).filter(([, v]) => v && !v.missingGroups.length).map(([k]) => k);
      console.log(`  display languages complete: ${ok.join(" ") || "none"}`);
      for (const w of r.warnings) console.log(`  ! ${w}`);
      console.log(r.healthy ? "  => the rules bundle is installed and readable." : "  => the rules bundle is NOT usable.");
    }
    // Exit 2 means one thing: no usable bundle at all. An engine and a data/ that
    // are both present but missing one file is a different failure — the other files
    // ARE readable, so the bodies' "only just proven absent" reasoning does not apply.
    const nothingReadable = Object.entries(r.counts)
      .filter(([k]) => k !== "progressionClasses").every(([, v]) => !v);
    process.exit(r.healthy ? 0 : _catalogConfig?.manifest ? 1 : nothingReadable ? 2 : 1);
  }

  const renderOptions = (cmd === "build" || cmd === "check")
    ? parseRenderOptions(rest, cmd)
    : null;
  const lang = renderOptions ? renderOptions.lang : parseLang(rest);
  if (cmd && !renderOptions) rejectUnknownFlags(cmd, rest);
  if (!cmd || !file) {
    console.error(`usage: node engine/cli.mjs <${COMMANDS.join("|")}> <file.json|classId> ` +
      `[--format html|markdown|json] [--lang en] [--output file] [--json] [--catalog dir]`);
    process.exit(USAGE);
  }
  if (COMMANDS.includes(cmd) && _catalogConfig.errors.length) {
    for (const error of _catalogConfig.errors) console.error(`dnd: catalog error: ${error}`);
    process.exit(_catalogConfig.manifest ? 1 : 2);
  }

  if (cmd === "options") {
    const answers = readJSON(file);
    const cat = await loadCatalogNodeSync();
    const invalid = await validateAnswers(cat, answers);
    let res = await cmdOptions(answers);

    // A full spell list pushes one call past 15K chars, and answering one choice
    // at a time reaches ~136K cumulative — inside the band where harnesses
    // truncate silently, which would hand the agent a partial legal option set.
    const only = rest.includes("--only") ? rest[rest.indexOf("--only") + 1] : null;
    if (only) {
      res = { ...res, fixedPending: res.fixedPending.filter((c) => c.id === only),
              dynamicPending: res.dynamicPending.filter((c) => c.id === only) };
      if (!res.fixedPending.length && !res.dynamicPending.length) {
        console.error(`dnd: no pending choice with id "${only}". Run \`options\` with no --only to list them.`);
        process.exit(USAGE);
      }
    }
    if (rest.includes("--brief")) {
      const strip = (c) => ({ id: c.id, kind: c.kind, source: c.source, need: c.need,
                              optionCount: (c.options || []).length });
      res = { ...res, fixedPending: res.fixedPending.map((c) => ({ id: c.id, label: c.label, optionCount: (c.options || []).length })),
              dynamicPending: res.dynamicPending.map(strip) };
    }
    // Diagnostics on stderr so stdout stays pure JSON for the agent to parse.
    for (const p of invalid) console.error(`dnd: ${p}`);
    console.log(JSON.stringify({ ...res, invalidAnswers: invalid }, null, 2));
    process.exit(invalid.length ? 1 : 0);
  }

  if (cmd === "progression") {
    const id = file; // here the argument is a class/subclass id, not a file
    const prog = loadData("progression.json");
    if (prog.classes && prog.classes[id]) {
      console.log(JSON.stringify({ class: id, ...prog.classes[id] }, null, 2));
      process.exit(0);
    }
    const sub = loadData("subclasses.json").find((s) => s.id === id);
    if (sub) {
      const featuresByLevel = {};
      for (const e of sub.effects || []) {
        if (e.what === "feature" && e.level) (featuresByLevel[e.level] ||= []).push(e.name);
      }
      console.log(JSON.stringify({
        subclass: id, parentClass: sub.parentClass, unlockedAtLevel: sub.level,
        source: sub.source, ref: sub.ref, featuresByLevel,
      }, null, 2));
      process.exit(0);
    }
    console.error(`Manquant documentaire : "${id}" n'est ni une classe ni une sous-classe du catalogue.`);
    process.exit(1);
  }

  if (cmd === "build" || cmd === "check") {
    let catalogGaps = [];
    let legacyWarnings = [];
    let model;
    const cat = await loadCatalogNodeSync();
    if (cmd === "build") {
      const answers = readJSON(file);

      // An illegal value must never reach the sheet: it computes from nothing
      // and renders `undefined` under a green lint.
      const invalid = await validateAnswers(cat, answers);
      if (invalid.length) {
        for (const p of invalid) console.error(`dnd: ${p}`);
        console.error("dnd: refusing to build from illegal answers.");
        process.exit(1);
      }

      // `build` used to ignore `ready`, so an unfinished file produced a sheet
      // that reported "no remaining choices" and 0 lint errors while silently
      // defaulting scores to 10 and merging every equipment package.
      const state = await cmdOptions(answers);
      if (!state.ready) {
        const pending = [
          ...state.fixedPending.map((f) => f.id),
          ...state.dynamicPending.map((d) => d.id),
        ];
        console.error(`dnd: answers are incomplete — ${pending.length} choice(s) still pending: ${pending.join(", ")}.`);
        console.error("dnd: run `options` and answer them; a sheet built from an incomplete file is not legal even when the lint is clean.");
        process.exit(1);
      }
      model = toCharacterModel(cat, answers);
    } else {
      model = readJSON(file);
      if (!model || !Array.isArray(model.sources)) {
        console.error(`dnd: "${file}" is not a character model (no \`sources\` array).`);
        console.error("dnd: if this is an answers file, use `build` instead; `check` expects a built model.");
        process.exit(USAGE);
      }

      // An empty model has nothing to audit; recomputing it printed `undefined`
      // values under a clean lint.
      if (!model.sources.length) {
        console.error("dnd: the `sources` array is empty — there is no character to check.");
        process.exit(USAGE);
      }
      legacyWarnings = resolveLegacyModelIds(cat, model);

      // `check` recomputes whatever it is handed, so a sheet naming entities the
      // catalog does not define used to lint clean. Report them — do not refuse:
      // an absent entry is "Manquant documentaire" for the audit to relay, not a
      // rules violation. Source ids are DERIVED (`druide-1`, not `druid`), so this
      // matches on the catalog id being contained in the source id, and stays a
      // warning precisely because that match is approximate.
      //
      // Source ids are DERIVED FROM THE FRENCH NAME (`clerc-1`, `tieffelin-abyssal`)
      // while catalog ids are English slugs (`cleric`, `tiefling`). Matching on the
      // id alone therefore flagged every correctly built character, including both
      // shipped under docs/characters/ — and a false "Manquant documentaire" on a
      // legal sheet is exactly the mistake the audit exists to avoid. Match a slug
      // of the entity's own `name` too.
      const slug = (v) => String(v || "").normalize("NFD").replace(/[\u0300-\u036f]/g, "")
        .toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
      const known = [];
      for (const e of [...cat.classes, ...cat.subclasses, ...cat.species, ...cat.backgrounds, ...cat.feats]) {
        known.push(e.id, slug(e.name));
        for (const l of e.lineages || []) known.push(l.id, slug(l.name));
      }
      catalogGaps = model.sources
        .filter((s) => ["class-level", "subclass", "species", "lineage", "background", "feat"].includes(s.kind))
        .filter((s) => s.id !== "origine-langues")
        .filter((s) => {
          if (s.catalogId && known.includes(s.catalogId)) return false;
          const id = slug(s.id);
          return !known.some((k) => k && (id === k || id.startsWith(k + "-")));
        })
        .map((s) => `${s.kind} "${s.id}"`);
      for (const u of catalogGaps) {
        console.error(`dnd: Manquant documentaire : ${u} matches no catalog entry — report it as a gap, not as an illegal value.`);
      }
    }
    const C = computeCharacter(model);
    C.problems.push(...legacyWarnings);
    C.problems.push(...spellLevelProblems(C, cat));
    if (renderOptions.format === "json") {
      // A gap visible only on stderr is invisible to an agent capturing stdout —
      // which is what `--json` is for, and what dnd-check's workflow tells it to do.
      // It saw `problems: []` on a sheet carrying a Pathfinder feat.
      const summary = summarize(C);
      const gapProblems = catalogGaps.map((detail) => ({
        level: "warn", code: "catalog-gap", params: { detail },
        msg: `Manquant documentaire : ${detail}`,
      }));
      emit({ ...summary, problems: [...summary.problems, ...gapProblems], catalogGaps });
    } else {
      const labels = loadLabels(lang);
      const context = {
        lang,
        labels,
        fallbackLabels: loadLabels("en"),
        ui: loadUiLabels(),
        mode: "standalone",
        source: displaySource(file),
        catalogGaps,
      };
      if (renderOptions.format === "html") {
        for (const problem of C.problems) {
          const level = problem.level === "error" ? "error" : "warning";
          console.error(`dnd: ${level}: ${problem.msg}`);
        }
        const outPath = resolveOutputPath(file, cmd, renderOptions);
        mkdirSync(dirname(outPath), { recursive: true });
        writeFileSync(outPath, renderHTML(C, { ...context, assets: standaloneAssets() }), "utf8");
        console.log(`${cmd === "build" ? "sheet" : "audit"}: ${outPath}`);
      } else {
        const markdown = renderMarkdown(C, context);
        if (renderOptions.output) {
          const outPath = resolveOutputPath(file, cmd, renderOptions);
          mkdirSync(dirname(outPath), { recursive: true });
          writeFileSync(outPath, markdown, "utf8");
        }
        console.log(markdown);
      }
    }
    const errs = C.problems.filter((p) => p.level === "error");
    // An audit that cannot be told from a clean one by its exit code is not an audit.
    process.exit(errs.length || catalogGaps.length ? 1 : 0);
  }

  // Exit 2 means one thing only: the rules bundle is absent. It used to also mean
  // "unknown command", so `options` typed `option` licensed the degraded mode the
  // skills gate on exit 2 — a typo authorising D&D-from-memory.
  console.error(`dnd: unknown command "${cmd}". Legal commands: ${COMMANDS.join(" ")}.`);
  process.exit(USAGE);
}

// A crash is a bug in the engine, not a missing bundle and not a bad sheet; it
// gets its own code so no skill mistakes it for either.
run().catch((e) => { console.error(`dnd: internal error — ${e.stack || String(e)}`); process.exit(4); });
