function makeLabeler(lang, labels) {
  const en = lang === "en";
  const abil = (a) => (labels.abilities && labels.abilities[a]) || (lang === "fr" ? ABILITY_FR : ABILITY_EN)[a] || a;
  const map = (group, id, fallback) => (labels[group] && labels[group][id]) || fallback || id;
  return { en, abil, map };
}

