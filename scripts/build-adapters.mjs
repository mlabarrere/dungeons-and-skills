/* ==========================================================================
   build-adapters.mjs — generate thin per-platform adapters from ONE source.

   The canonical rule text is the `dnd-builder` section of AGENTS.md. This script
   copies that body verbatim into each host's native rule format (adding only the
   per-host frontmatter a given tool requires), and writes the Claude plugin
   manifests. Keep adapters thin: they never diverge from AGENTS.md. Drift is
   caught by scripts/check-rule-copies.mjs.

   Regenerate: node scripts/build-adapters.mjs
   ========================================================================== */
import { cpSync, readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync, rmSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

export function canonicalRule() {
  const agents = readFileSync(join(ROOT, "AGENTS.md"), "utf8").replace(/\r\n/g, "\n");
  const m = agents.match(/<!-- BEGIN:dnd-builder -->\n([\s\S]*?)\n<!-- END:dnd-builder -->/);
  if (!m) throw new Error("AGENTS.md: dnd-builder markers not found");
  return m[1].trim();
}

function write(rel, content) {
  const abs = join(ROOT, rel);
  mkdirSync(dirname(abs), { recursive: true });
  writeFileSync(abs, content.endsWith("\n") ? content : content + "\n", "utf8");
  return rel;
}

const GENERATED = "<!-- GENERATED from AGENTS.md by scripts/build-adapters.mjs — do not edit. -->\n";
export const AUTONOMOUS_SKILL = "dungeons-and-skills";

/* --------------------------------------------------------------------------
   Per-skill bundles.

   The Agent Skills spec makes a skill FOLDER the unit of distribution: a
   SKILL.md may not reference anything outside it, or a client that copies just
   that folder ships a broken skill. So each skill gets its own door to the
   engine (scripts/dnd.mjs) and its own copy of the rule texts it cites
   (references/). Both are generated here and drift-checked by
   check-rule-copies.mjs — the copies can never diverge from rules/.

   Nothing here is a hand-maintained list: skills are discovered on disk, and
   each one's references are derived from the links its SKILL.md actually makes.
   Add a skill, or link references/schema.md from an existing one, and the next
   generate picks it up. A hardcoded roster would silently skip a new skill.
   -------------------------------------------------------------------------- */

/** Every skill directory under skills/, sorted. */
export function listSkills() {
  return readdirSync(join(ROOT, "skills"), { withFileTypes: true })
    .filter((e) => e.isDirectory() && existsSync(join(ROOT, "skills", e.name, "SKILL.md")))
    .map((e) => e.name)
    .sort();
}

/** The rules/ files a skill cites, read off its own references/ links. */
export function referencesFor(skill) {
  const body = readFileSync(join(ROOT, "skills", skill, "SKILL.md"), "utf8");
  const names = new Set();
  for (const m of body.matchAll(/references\/([A-Za-z0-9_-]+\.md)/g)) {
    const name = m[1];
    if (!existsSync(join(ROOT, "rules", name))) {
      throw new Error(`skills/${skill}/SKILL.md links references/${name}, but rules/${name} does not exist`);
    }
    names.add(name);
  }
  return [...names].sort();
}

